-- Daraja M-PESA payment audit records and atomic transaction safeguards.
-- Apply this entire migration in Supabase before configuring merchant credentials.

create table if not exists public."paymentAttempts" (
  id bigint generated by default as identity primary key,
  "orderRequestId" bigint not null references public."orderRequests"(id) on delete restrict,
  provider text not null check (provider = 'safaricom_daraja'),
  status text not null check (status in ('initiating', 'pending', 'paid', 'failed', 'review')),
  "idempotencyKey" varchar(64) not null unique,
  amount bigint not null check (amount > 0),
  phone varchar(16) not null,
  "merchantRequestId" varchar(128),
  "checkoutRequestId" varchar(128) unique,
  "resultCode" varchar(32),
  "resultDescription" text,
  "mpesaReceiptNumber" varchar(32),
  "lastCallbackAt" timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);
alter table public."paymentAttempts" add column if not exists "lastCallbackAt" timestamptz;
drop index if exists public.payment_attempts_one_open_per_order_idx;
create unique index if not exists payment_attempts_one_open_or_paid_per_order_idx
  on public."paymentAttempts"("orderRequestId") where status in ('initiating', 'pending', 'review', 'paid');
create index if not exists payment_attempts_order_created_idx
  on public."paymentAttempts"("orderRequestId", "createdAt" desc);

create table if not exists public."darajaCallbackInbox" (
  id bigint generated by default as identity primary key,
  "checkoutRequestId" varchar(128) not null,
  "merchantRequestId" varchar(128) not null,
  payload jsonb not null check (jsonb_typeof(payload) = 'object'),
  "createdAt" timestamptz not null default now(),
  "processedAt" timestamptz
);
create unique index if not exists daraja_callback_inbox_one_unprocessed_idx
  on public."darajaCallbackInbox"("checkoutRequestId") where "processedAt" is null;
create index if not exists daraja_callback_inbox_created_idx on public."darajaCallbackInbox"("createdAt");

alter table public."paymentAttempts" enable row level security;
alter table public."darajaCallbackInbox" enable row level security;
revoke all on public."paymentAttempts" from anon, authenticated;
revoke all on public."darajaCallbackInbox" from anon, authenticated;
grant select, insert, update, delete on public."paymentAttempts" to service_role;
grant usage, select on sequence public."paymentAttempts_id_seq" to service_role;
grant select, insert, update, delete on public."darajaCallbackInbox" to service_role;
grant usage, select on sequence public."darajaCallbackInbox_id_seq" to service_role;

create or replace function public.guard_daraja_payment_attempt_insert()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
declare
  v_order public."orderRequests"%rowtype;
  v_customer_phone text;
  v_phone_digits text;
  v_item_count bigint;
  v_all_priced boolean;
  v_attempt_count bigint;
begin
  if new.provider <> 'safaricom_daraja' or new.status <> 'initiating' then raise exception 'Invalid initial payment-attempt state'; end if;
  select * into v_order from public."orderRequests" where id = new."orderRequestId" for update;
  if not found then raise exception 'Order request does not exist'; end if;
  if v_order.status <> 'confirmed' or v_order.total is null or v_order.total <= 0 or v_order.total <> new.amount then
    raise exception 'Order is not confirmed at the saved payable total';
  end if;
  select c.phone into v_customer_phone from public.customers c where c.id = v_order."customerId";
  if not found then raise exception 'Order customer does not exist'; end if;
  v_phone_digits := regexp_replace(coalesce(v_customer_phone, ''), '[^0-9]', '', 'g');
  if left(v_phone_digits, 3) <> '254' then
    if left(v_phone_digits, 1) = '0' then v_phone_digits := '254' || substr(v_phone_digits, 2);
    else v_phone_digits := '254' || v_phone_digits; end if;
  end if;
  if v_phone_digits !~ '^254[71][0-9]{8}$' or v_phone_digits <> new.phone then raise exception 'Saved customer phone does not match the payment attempt'; end if;
  select count(*), coalesce(bool_and(i."unitPrice" > 0), false) into v_item_count, v_all_priced
    from public."orderItems" i where i."orderRequestId" = new."orderRequestId";
  if v_item_count = 0 or not v_all_priced then raise exception 'Order contains unpriced or missing items'; end if;
  select count(*) into v_attempt_count from public."paymentAttempts" p
    where p."orderRequestId" = new."orderRequestId" and p."createdAt" >= now() - interval '10 minutes';
  if v_attempt_count >= 3 then raise exception 'Payment initiation rate limit exceeded'; end if;
  return new;
end;
$$;

create or replace function public.guard_daraja_order_status_change()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_blocking_statuses text[];
begin
  if new.status is not distinct from old.status then return new; end if;
  if new.status in ('cancelled', 'new') then v_blocking_statuses := array['initiating', 'pending', 'review', 'paid'];
  else v_blocking_statuses := array['initiating', 'pending', 'review']; end if;
  perform 1 from public."paymentAttempts" p where p."orderRequestId" = old.id and p.status = any(v_blocking_statuses) for update;
  if found then raise exception 'Order status cannot change while an M-PESA attempt is active, under review or paid'; end if;
  return new;
end;
$$;

create or replace function public.protect_daraja_payment_attempt_update()
returns trigger language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  if new."orderRequestId" is distinct from old."orderRequestId" or new.provider is distinct from old.provider
     or new."idempotencyKey" is distinct from old."idempotencyKey" or new.amount is distinct from old.amount
     or new.phone is distinct from old.phone then raise exception 'Payment attempt identity and saved payment values are immutable'; end if;
  if old.status = 'paid' and new.status <> 'paid' then raise exception 'Verified payment status is terminal'; end if;
  if new.status = 'paid' and old.status <> 'paid'
     and current_setting('dph.verified_daraja_payment', true) is distinct from 'true' then
    raise exception 'Payment can only be marked paid by provider reconciliation';
  end if;
  if old."checkoutRequestId" is not null and new."checkoutRequestId" is distinct from old."checkoutRequestId" then
    raise exception 'Daraja checkout identifier is immutable'; end if;
  return new;
end;
$$;

drop trigger if exists trg_guard_daraja_payment_attempt_insert on public."paymentAttempts";
create trigger trg_guard_daraja_payment_attempt_insert before insert on public."paymentAttempts"
  for each row execute function public.guard_daraja_payment_attempt_insert();
drop trigger if exists trg_guard_daraja_order_status_change on public."orderRequests";
create trigger trg_guard_daraja_order_status_change before update of status on public."orderRequests"
  for each row execute function public.guard_daraja_order_status_change();
drop trigger if exists trg_protect_daraja_payment_attempt_update on public."paymentAttempts";
create trigger trg_protect_daraja_payment_attempt_update before update on public."paymentAttempts"
  for each row execute function public.protect_daraja_payment_attempt_update();

create or replace function public.claim_daraja_callback(p_checkout_request_id text)
returns boolean language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_attempt public."paymentAttempts"%rowtype;
begin
  select * into v_attempt from public."paymentAttempts" where "checkoutRequestId" = p_checkout_request_id for update;
  if not found or v_attempt.status = 'paid' then return false; end if;
  if v_attempt."lastCallbackAt" is not null and v_attempt."lastCallbackAt" > now() - interval '5 seconds' then return false; end if;
  update public."paymentAttempts" set "lastCallbackAt" = now(), "updatedAt" = now() where id = v_attempt.id;
  return true;
end;
$$;

create or replace function public.store_daraja_callback(p_checkout_request_id text, p_merchant_request_id text, p_payload jsonb)
returns boolean language plpgsql security definer set search_path = pg_catalog, public as $$
declare v_pending_count bigint;
begin
  if p_checkout_request_id is null or length(p_checkout_request_id) < 1 or length(p_checkout_request_id) > 128
     or p_merchant_request_id is null or length(p_merchant_request_id) < 1 or length(p_merchant_request_id) > 128
     or p_payload is null or jsonb_typeof(p_payload) <> 'object' or pg_column_size(p_payload) > 65536 then
    raise exception 'Invalid or oversized callback payload';
  end if;
  perform pg_advisory_xact_lock(hashtext('dph-daraja-callback-inbox'));
  delete from public."darajaCallbackInbox"
    where ("processedAt" is not null and "processedAt" < now() - interval '30 days')
       or ("processedAt" is null and "createdAt" < now() - interval '1 hour');
  select count(*) into v_pending_count from public."darajaCallbackInbox" where "processedAt" is null;
  if v_pending_count >= 100 then raise exception 'Callback reconciliation inbox is full'; end if;
  insert into public."darajaCallbackInbox"("checkoutRequestId", "merchantRequestId", payload)
    values (p_checkout_request_id, p_merchant_request_id, p_payload)
    on conflict ("checkoutRequestId") where "processedAt" is null do nothing;
  return true;
end;
$$;

create or replace function public.get_daraja_callback(p_checkout_request_id text)
returns jsonb language sql security definer set search_path = pg_catalog, public as $$
  select payload from public."darajaCallbackInbox"
  where "checkoutRequestId" = p_checkout_request_id and "processedAt" is null order by id desc limit 1;
$$;
create or replace function public.mark_daraja_callback_processed(p_checkout_request_id text)
returns boolean language plpgsql security definer set search_path = pg_catalog, public as $$
begin
  update public."darajaCallbackInbox" set "processedAt" = now()
  where "checkoutRequestId" = p_checkout_request_id and "processedAt" is null;
  return found;
end;
$$;

create or replace function public.record_verified_daraja_payment(
  p_attempt_id bigint, p_checkout_request_id text, p_merchant_request_id text, p_result_description text
)
returns boolean language plpgsql security definer set search_path = pg_catalog, public as $$
declare
  v_attempt public."paymentAttempts"%rowtype;
  v_order public."orderRequests"%rowtype;
  v_customer_phone text;
  v_phone_digits text;
  v_item_count bigint;
  v_all_priced boolean;
begin
  select * into v_attempt from public."paymentAttempts" where id = p_attempt_id;
  if not found then raise exception 'Payment attempt does not exist'; end if;
  select * into v_order from public."orderRequests" where id = v_attempt."orderRequestId" for update;
  if not found then raise exception 'Payment order does not exist'; end if;
  select * into v_attempt from public."paymentAttempts" where id = p_attempt_id for update;
  if v_attempt.status = 'paid' then return true; end if;
  if v_attempt.status not in ('initiating', 'pending', 'review', 'failed') then return false; end if;
  if v_attempt."checkoutRequestId" is distinct from p_checkout_request_id or v_attempt."merchantRequestId" is distinct from p_merchant_request_id then
    update public."paymentAttempts" set status = 'review', "resultCode" = 'IDENTIFIER_MISMATCH',
      "resultDescription" = 'Provider identifiers did not match the saved attempt.', "updatedAt" = now() where id = v_attempt.id;
    return false;
  end if;
  if v_order.status <> 'confirmed' or v_order.total is null or v_order.total <> v_attempt.amount then
    update public."paymentAttempts" set status = 'review', "resultCode" = 'ORDER_MISMATCH',
      "resultDescription" = 'Verified payment did not match the current confirmed order total.', "updatedAt" = now() where id = v_attempt.id;
    return false;
  end if;
  select c.phone into v_customer_phone from public.customers c where c.id = v_order."customerId";
  v_phone_digits := regexp_replace(coalesce(v_customer_phone, ''), '[^0-9]', '', 'g');
  if left(v_phone_digits, 3) <> '254' then
    if left(v_phone_digits, 1) = '0' then v_phone_digits := '254' || substr(v_phone_digits, 2);
    else v_phone_digits := '254' || v_phone_digits; end if;
  end if;
  if v_phone_digits !~ '^254[71][0-9]{8}$' or v_phone_digits <> v_attempt.phone then
    update public."paymentAttempts" set status = 'review', "resultCode" = 'PHONE_MISMATCH',
      "resultDescription" = 'Saved customer phone changed after the payment prompt was created.', "updatedAt" = now() where id = v_attempt.id;
    return false;
  end if;
  select count(*), coalesce(bool_and(i."unitPrice" > 0), false) into v_item_count, v_all_priced
    from public."orderItems" i where i."orderRequestId" = v_attempt."orderRequestId";
  if v_item_count = 0 or not v_all_priced then
    update public."paymentAttempts" set status = 'review', "resultCode" = 'UNPRICED_ITEMS',
      "resultDescription" = 'Order contains unpriced or missing items.', "updatedAt" = now() where id = v_attempt.id;
    return false;
  end if;
  if exists (select 1 from public."paymentAttempts" other_attempt
      where other_attempt."orderRequestId" = v_attempt."orderRequestId" and other_attempt.id <> v_attempt.id
        and other_attempt.status in ('initiating', 'pending', 'review', 'paid')) then
    update public."paymentAttempts" set status = 'review', "resultCode" = 'CONCURRENT_ATTEMPT',
      "resultDescription" = 'Another payment attempt exists; service-desk reconciliation is required.', "updatedAt" = now() where id = v_attempt.id;
    return false;
  end if;
  perform set_config('dph.verified_daraja_payment', 'true', true);
  update public."paymentAttempts" set status = 'paid', "resultCode" = '0',
    "resultDescription" = left(coalesce(p_result_description, 'Provider query confirmed M-PESA payment.'), 500),
    "mpesaReceiptNumber" = null, "updatedAt" = now() where id = v_attempt.id;
  return true;
end;
$$;

create or replace function public.daraja_payment_ready()
returns boolean language sql security definer set search_path = pg_catalog, public as $$
  select to_regclass('public."paymentAttempts"') is not null
    and to_regclass('public."darajaCallbackInbox"') is not null
    and to_regprocedure('public.record_verified_daraja_payment(bigint,text,text,text)') is not null
    and to_regprocedure('public.store_daraja_callback(text,text,jsonb)') is not null
    and to_regprocedure('public.claim_daraja_callback(text)') is not null
    and to_regprocedure('public.get_daraja_callback(text)') is not null
    and to_regprocedure('public.mark_daraja_callback_processed(text)') is not null
    and (select c.relrowsecurity from pg_class c where c.oid = to_regclass('public."paymentAttempts"')) is true
    and (select c.relrowsecurity from pg_class c where c.oid = to_regclass('public."darajaCallbackInbox"')) is true
    and (select count(*) = 15 from information_schema.columns c
      where c.table_schema = 'public' and c.table_name = 'paymentAttempts'
        and c.column_name = any(array['id','orderRequestId','provider','status','idempotencyKey','amount','phone','merchantRequestId','checkoutRequestId','resultCode','resultDescription','mpesaReceiptNumber','lastCallbackAt','createdAt','updatedAt']))
    and (select count(*) = 6 from information_schema.columns c
      where c.table_schema = 'public' and c.table_name = 'darajaCallbackInbox'
        and c.column_name = any(array['id','checkoutRequestId','merchantRequestId','payload','createdAt','processedAt']))
    and exists (select 1 from pg_index i where i.indexrelid = to_regclass('public.payment_attempts_one_open_or_paid_per_order_idx') and i.indisunique and i.indpred is not null)
    and exists (select 1 from pg_index i where i.indexrelid = to_regclass('public.daraja_callback_inbox_one_unprocessed_idx') and i.indisunique and i.indpred is not null)
    and exists (select 1 from pg_trigger t where t.tgrelid = to_regclass('public."paymentAttempts"') and t.tgname = 'trg_guard_daraja_payment_attempt_insert' and t.tgenabled <> 'D' and not t.tgisinternal)
    and exists (select 1 from pg_trigger t where t.tgrelid = to_regclass('public."orderRequests"') and t.tgname = 'trg_guard_daraja_order_status_change' and t.tgenabled <> 'D' and not t.tgisinternal)
    and exists (select 1 from pg_trigger t where t.tgrelid = to_regclass('public."paymentAttempts"') and t.tgname = 'trg_protect_daraja_payment_attempt_update' and t.tgenabled <> 'D' and not t.tgisinternal)
    and has_table_privilege('service_role', 'public."paymentAttempts"', 'SELECT')
    and has_table_privilege('service_role', 'public."paymentAttempts"', 'INSERT')
    and has_table_privilege('service_role', 'public."paymentAttempts"', 'UPDATE')
    and has_table_privilege('service_role', 'public."darajaCallbackInbox"', 'SELECT')
    and has_table_privilege('service_role', 'public."darajaCallbackInbox"', 'INSERT')
    and has_table_privilege('service_role', 'public."darajaCallbackInbox"', 'UPDATE')
    and has_sequence_privilege('service_role', 'public."paymentAttempts_id_seq"', 'USAGE')
    and has_sequence_privilege('service_role', 'public."darajaCallbackInbox_id_seq"', 'USAGE')
    and has_function_privilege('service_role', 'public.record_verified_daraja_payment(bigint,text,text,text)', 'EXECUTE')
    and has_function_privilege('service_role', 'public.store_daraja_callback(text,text,jsonb)', 'EXECUTE')
    and has_function_privilege('service_role', 'public.claim_daraja_callback(text)', 'EXECUTE')
    and has_function_privilege('service_role', 'public.get_daraja_callback(text)', 'EXECUTE')
    and has_function_privilege('service_role', 'public.mark_daraja_callback_processed(text)', 'EXECUTE')
    and not has_table_privilege('anon', 'public."paymentAttempts"', 'SELECT')
    and not has_table_privilege('authenticated', 'public."paymentAttempts"', 'SELECT')
    and not has_table_privilege('anon', 'public."darajaCallbackInbox"', 'SELECT')
    and not has_table_privilege('authenticated', 'public."darajaCallbackInbox"', 'SELECT')
    and not has_function_privilege('anon', 'public.record_verified_daraja_payment(bigint,text,text,text)', 'EXECUTE')
    and not has_function_privilege('authenticated', 'public.record_verified_daraja_payment(bigint,text,text,text)', 'EXECUTE');
$$;

