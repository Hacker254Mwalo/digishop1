-- Digital Phone Hub initial Supabase schema
-- Safe to run on the currently empty project.

create table if not exists public.users (
  id bigint generated by default as identity primary key,
  "openId" varchar(64) not null unique,
  name text,
  email varchar(320),
  "loginMethod" varchar(64),
  role text not null default 'user' check (role in ('user', 'admin')),
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now(),
  "lastSignedIn" timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name varchar(160) not null,
  phone varchar(40) not null,
  email varchar(320),
  location varchar(180),
  notes text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public.technicians (
  id bigint generated by default as identity primary key,
  name varchar(160) not null,
  phone varchar(40),
  specialty varchar(160),
  active boolean not null default true,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public.devices (
  id bigint generated by default as identity primary key,
  "customerId" bigint not null references public.customers(id) on delete cascade,
  type text not null check (type in ('phone', 'laptop', 'tablet', 'other')),
  brand varchar(100) not null,
  model varchar(160) not null,
  "serialNumber" varchar(160),
  notes text,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public."repairTickets" (
  id bigint generated by default as identity primary key,
  reference varchar(32) not null unique,
  "customerId" bigint not null references public.customers(id) on delete cascade,
  "deviceId" bigint not null references public.devices(id) on delete cascade,
  "technicianId" bigint references public.technicians(id) on delete set null,
  issue text not null,
  priority text not null default 'normal' check (priority in ('low', 'normal', 'high', 'urgent')),
  status text not null default 'received' check (status in ('received', 'diagnostics', 'awaiting_approval', 'in_repair', 'ready', 'collected', 'cancelled')),
  "quotedAmount" bigint,
  "receivedAt" timestamptz not null default now(),
  "completedAt" timestamptz,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public."repairNotes" (
  id bigint generated by default as identity primary key,
  "ticketId" bigint not null references public."repairTickets"(id) on delete cascade,
  "authorId" bigint references public.users(id) on delete set null,
  note text not null,
  "createdAt" timestamptz not null default now()
);

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku varchar(80) not null unique,
  name varchar(180) not null,
  category text not null check (category in ('phone_screen', 'charging_port', 'battery', 'laptop_spare', 'accessory', 'other')),
  description text,
  compatibility text,
  price bigint not null,
  stock bigint not null default 0,
  "reorderLevel" bigint not null default 2,
  availability text not null default 'in_stock' check (availability in ('in_stock', 'low_stock', 'out_of_stock', 'by_order')),
  active boolean not null default true,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public."orderRequests" (
  id bigint generated by default as identity primary key,
  reference varchar(32) not null unique,
  "customerId" bigint not null references public.customers(id) on delete cascade,
  status text not null default 'new' check (status in ('new', 'confirmed', 'fulfilled', 'cancelled')),
  fulfillment text not null check (fulfillment in ('delivery', 'collection')),
  "deliveryLocation" varchar(180),
  notes text,
  total bigint,
  "createdAt" timestamptz not null default now(),
  "updatedAt" timestamptz not null default now()
);

create table if not exists public."orderItems" (
  id bigint generated by default as identity primary key,
  "orderRequestId" bigint not null references public."orderRequests"(id) on delete cascade,
  "productId" bigint references public.products(id) on delete set null,
  "productNameSnapshot" varchar(180) not null,
  quantity bigint not null check (quantity > 0),
  "unitPrice" bigint not null check ("unitPrice" >= 0),
  "createdAt" timestamptz not null default now()
);

create index if not exists customers_phone_idx on public.customers(phone);
create index if not exists repair_tickets_status_idx on public."repairTickets"(status);
create index if not exists repair_tickets_customer_idx on public."repairTickets"("customerId");
create index if not exists order_requests_status_idx on public."orderRequests"(status);

